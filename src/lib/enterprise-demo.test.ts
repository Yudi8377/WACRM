import { describe, expect, it } from "vitest";
import { createDemoWorkspaceAdapter } from "./demo-store";

describe("Enterprise Autonomous Suite Demo Adapter (AI + POS QR + ERP + Accounting)", () => {
  it("loads seeded AI agents, knowledge base, ERP products, POS orders, and balanced accounting ledger", async () => {
    const adapter = createDemoWorkspaceAdapter();
    await adapter.resetDemo?.();
    const snap = await adapter.loadAll();

    expect(snap.aiAgents.length).toBe(5);
    expect(snap.aiKnowledge.length).toBeGreaterThanOrEqual(7);
    expect(snap.products.length).toBeGreaterThanOrEqual(6);
    expect(snap.suppliers.length).toBeGreaterThanOrEqual(3);
    expect(snap.orders.length).toBeGreaterThanOrEqual(3);
    expect(snap.financialReport.isBalanced).toBe(true);
    expect(snap.financialReport.totalDebits).toBe(snap.financialReport.totalCredits);
  });

  it("auto-replies via Multi-Agent AI, creates POS order with QR, deducts ERP stock & posts balanced journal", async () => {
    const adapter = createDemoWorkspaceAdapter();
    await adapter.resetDemo?.();
    const before = await adapter.loadAll();
    const convId = before.conversations[0].id;
    const kopiBefore = before.products.find((p) => p.sku === "KOPI-GAYO")!;

    const result = await adapter.runAiAutoReply(
      convId,
      "Halo kak, saya pesan 2 Kopi Arabika Gayo kirim ke Jl. Dhoho 12 Kediri bayar QRIS ya!",
    );

    expect(result.createdOrder).not.toBeNull();
    expect(result.createdOrder?.aiGenerated).toBe(true);
    expect(result.createdOrder?.qrPayload).toContain("WACRM-QRIS|");
    expect(result.createdOrder?.shippingAddress.toLowerCase()).toContain("dhoho");

    const after = await adapter.loadAll();
    const kopiAfter = after.products.find((p) => p.sku === "KOPI-GAYO")!;
    expect(kopiAfter.stockQty).toBe(kopiBefore.stockQty - 2);
    expect(after.orders.length).toBe(before.orders.length + 1);
    expect(after.financialReport.isBalanced).toBe(true);
  });

  it("creates ERP product and automatically adds it to the AI Knowledge Base", async () => {
    const adapter = createDemoWorkspaceAdapter();
    await adapter.resetDemo?.();

    const created = await adapter.createProduct({
      sku: "TEH-HIJAU-100",
      name: "Teh Hijau Organik 100gr",
      category: "Minuman",
      unitPrice: 75000,
      costPrice: 40000,
      stockQty: 25,
      minStock: 5,
      description: "Teh hijau pegunungan.",
    });

    const snap = await adapter.loadAll();
    expect(snap.products.some((p) => p.id === created.id)).toBe(true);
    expect(snap.aiKnowledge.some((k) => k.sourceId === created.id && k.autoGenerated)).toBe(true);
  });

  it("runs Guardian self-healing scan and creates balanced manual accounting entries", async () => {
    const adapter = createDemoWorkspaceAdapter();
    await adapter.resetDemo?.();

    const je = await adapter.createAccountingEntry({
      kind: "expense",
      categoryName: "Internet Kantor",
      amount: 450000,
      description: "Tagihan fiber optik bulanan",
    });
    expect(je.entryNumber).toContain("JE-MAN-");

    const scan = await adapter.runAiGuardianScan();
    expect(scan.healthScore).toBeGreaterThanOrEqual(50);

    const snap = await adapter.loadAll();
    expect(snap.financialReport.isBalanced).toBe(true);
  });
});
